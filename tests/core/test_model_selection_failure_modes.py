"""Regimes in which the likelihood ratio test is known to be unreliable.

The Bayesian selector is claimed to detect the Markov order more reliably than the likelihood
ratio test, to need considerably less data, and to be robust against partial knowledge of the
underlying graph.[^1] These tests pin down the behaviour of both selectors in those regimes.

Warning: These expectations are empirical, and pinned to a seed
    Unlike the rest of the test suite, the expected orders here are not derived from a formula:
    they are what the two procedures happen to report on data generated with the stated seed and
    sample size. A change to the random number generator, to torch, or to the generators in
    [`temporal_generative_models`][pathpyG.algorithms.temporal_generative_models] can move the
    boundary of a regime and make a test fail without anything being wrong with the selectors.

    If one of these fails, first re-characterise the scenario -- sweep the sample size and print
    what each selector returns -- and only then look for a regression. Every test states the
    generator arguments it uses so that the sweep can be reproduced.

[^1]: *L Petrović, I Scholtes: Learning the Markov Order of Paths in Graphs, In Proc. of the ACM
    Web Conference (WWW'22), 2022.
    [doi:10.1145/3485447.3512091](https://doi.org/10.1145/3485447.3512091)*
"""

# pylint: disable=missing-function-docstring

import pytest
import torch

from pathpyG.algorithms.temporal_generative_models import higher_order_block_walks
from pathpyG.core.graph import Graph
from pathpyG.core.index_map import IndexMap
from pathpyG.core.multi_order_model import MultiOrderModel

NUM_NODES = 9
NUM_CLUSTERS = 3


def second_order_walks(num_walks: int, seed: int = 0):
    """A temporal graph whose true Markov order is two, with `num_walks` observations."""
    return higher_order_block_walks(
        num_nodes=NUM_NODES,
        num_clusters=NUM_CLUSTERS,
        num_walks=num_walks,
        order=2,
        walk_length=3,
        intra_cluster_probability=0.95,
        walk_separation=4,
        seed=seed,
    )


def first_order_walks(num_walks: int, seed: int = 0):
    """A temporal graph whose true Markov order is one, with `num_walks` observations."""
    return higher_order_block_walks(
        num_nodes=NUM_NODES,
        num_clusters=NUM_CLUSTERS,
        num_walks=num_walks,
        order=1,
        walk_length=3,
        intra_cluster_probability=0.9,
        walk_separation=4,
        seed=seed,
    )


def complete_graph(num_nodes: int) -> Graph:
    """Every ordered pair of nodes, i.e. the topology the generator could have produced."""
    sources = torch.arange(num_nodes).repeat_interleave(num_nodes)
    destinations = torch.arange(num_nodes).repeat(num_nodes)
    return Graph.from_edge_index(
        torch.stack([sources, destinations]),
        num_nodes=num_nodes,
        mapping=IndexMap(list(range(num_nodes))),
    )


@pytest.mark.parametrize("num_walks", [60, 120])
def test_likelihood_ratio_test_underfits_on_scarce_data(num_walks):
    """With few observations the test cannot reject order zero, while the Bayes factor can.

    Generated by `second_order_walks(num_walks, seed=0)`: nine nodes in three clusters, walks of
    three events, `intra_cluster_probability=0.95`. Empirical for this seed, see the module
    docstring.
    """
    model = MultiOrderModel.from_temporal_graph(second_order_walks(num_walks), delta=1, max_order=3)
    assert model.estimate_order(method="likelihood_ratio") == 0
    assert model.estimate_order(method="bayesian") == 2


@pytest.mark.parametrize("num_walks", [250, 1000])
def test_both_selectors_agree_once_there_is_enough_data(num_walks):
    """The same generator at a larger sample size, so the scarce-data test cannot pass by accident."""
    model = MultiOrderModel.from_temporal_graph(second_order_walks(num_walks), delta=1, max_order=3)
    assert model.estimate_order(method="likelihood_ratio") == 2
    assert model.estimate_order(method="bayesian") == 2


@pytest.mark.parametrize("seed", [0, 1, 2, 3, 4])
def test_neither_selector_overfits_a_first_order_process(seed):
    """On data with no structure beyond the first order, neither selector reports a higher one.

    Generated by `first_order_walks(200, seed)`. This is a calibration check: the likelihood ratio
    test is often said to overfit on small or partially observed data, but with the graph-constrained
    parameter count it does not do so here, and neither does the Bayes factor.
    """
    model = MultiOrderModel.from_temporal_graph(first_order_walks(200, seed=seed), delta=1, max_order=3)
    assert model.estimate_order(method="likelihood_ratio") == 1
    assert model.estimate_order(method="bayesian") == 1


def test_partially_observed_graph_changes_the_parameter_count():
    """Counting parameters over the observed transitions alone badly undercounts them.

    The generator can emit any of the 81 ordered node pairs, but a sample of 200 walks realizes
    only a fraction of them. Counting free parameters over the observed subgraph is what
    `constraint_graph=None` does, and it is the step the Bayesian paper identifies as conflating
    the underlying network with the transitions that happen to be observed.
    """
    model = MultiOrderModel.from_temporal_graph(first_order_walks(200, seed=0), delta=1, max_order=2)
    known_graph = complete_graph(NUM_NODES)

    observed_edges = torch.unique(model.layers[1].data.edge_index.as_tensor(), dim=1).size(1)
    assert observed_edges < NUM_NODES * NUM_NODES

    inferred = model.degrees_of_freedom(max_order=2)
    known = model.degrees_of_freedom(max_order=2, constraint_graph=known_graph)
    # A complete graph on n nodes has (n - 1) + n(n - 1) + n^2(n - 1) = n^3 - 1 free parameters.
    assert known == NUM_NODES**3 - 1 == 728
    assert inferred == 346
    assert known > 2 * inferred


def test_the_constraint_graph_does_not_change_these_decisions():
    """Supplying the true topology moves the parameter count a lot but not the verdict here.

    Documented as a characterisation test: the degrees of freedom differ by more than a factor of
    four (see the test above), yet both selectors return the true order either way at this sample
    size. If a future change makes the two disagree, that is worth understanding rather than
    silently accepting.
    """
    known_graph = complete_graph(NUM_NODES)

    first_order = MultiOrderModel.from_temporal_graph(first_order_walks(400), delta=1, max_order=3)
    assert first_order.estimate_order(method="likelihood_ratio") == 1
    assert first_order.estimate_order(method="likelihood_ratio", constraint_graph=known_graph) == 1
    assert first_order.estimate_order(method="bayesian", constraint_graph=known_graph) == 1

    second_order = MultiOrderModel.from_temporal_graph(second_order_walks(400), delta=1, max_order=3)
    assert second_order.estimate_order(method="likelihood_ratio") == 2
    assert second_order.estimate_order(method="likelihood_ratio", constraint_graph=known_graph) == 2
    assert second_order.estimate_order(method="bayesian", constraint_graph=known_graph) == 2
